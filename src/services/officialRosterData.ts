export function detectPreferredTitle(fullName: string): 'nurse_m' | 'nurse_f' {
  const firstWord = fullName.trim().split(/\s+/)[0]?.toLowerCase() || '';
  const cleanWord = firstWord
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي');

  for (const fem of FEMALE_PREFIXES) {
    const cleanFem = fem
      .replace(/[أإآٱ]/g, 'ا')
      .replace(/ة/g, 'ه')
      .replace(/ى/g, 'ي');
    if (cleanWord === cleanFem) return 'nurse_f';
  }
  return 'nurse_m';
}

export function buildOfficial244Roster(): OfficialRosterStudent[] {
  const sections: Array<{
    name: 'شعبة 1' | 'شعبة 2' | 'شعبة 3' | 'شعبة 4';
    num: 1 | 2 | 3 | 4;
    list: string[];
  }> = [
    { name: 'شعبة 1', num: 1, list: SECTION_1_STUDENTS },
    { name: 'شعبة 2', num: 2, list: SECTION_2_STUDENTS },
    { name: 'شعبة 3', num: 3, list: SECTION_3_STUDENTS },
    { name: 'شعبة 4', num: 4, list: SECTION_4_STUDENTS },
  ];

  const roster: OfficialRosterStudent[] = [];
  let globalNum = 1;

  for (const sec of sections) {
    sec.list.forEach((name, idx) => {
      roster.push({
        globalNumber: globalNum++,
        section: sec.name,
        sectionNumber: sec.num,
        sectionIndex: idx + 1,
        fullName: name.trim(),
        preferredTitle: detectPreferredTitle(name),
        totalFeeIQD: 35000,
      });
    });
  }

  return roster;
}

export const OFFICIAL_244_ROSTER: OfficialRosterStudent[] = buildOfficial244Roster();
